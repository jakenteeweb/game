import type { Point, Stroke } from './types';

/** Дуга эллипса: углы в градусах, 0° — справа, 90° — снизу (экранные координаты). */
export function arc(cx: number, cy: number, rx: number, ry: number, fromDeg: number, toDeg: number, steps = 16): Point[] {
  const pts: Point[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((fromDeg + ((toDeg - fromDeg) * i) / steps) * Math.PI) / 180;
    pts.push([round(cx + rx * Math.cos(a)), round(cy + ry * Math.sin(a))]);
  }
  return pts;
}

const round = (n: number) => Math.round(n * 10) / 10;

const L = (...pts: Point[]): Point[] => pts;
/** Нижняя «чаша» букв Б, В, Ъ, Ь, Ы: горизонталь от стойки и полукруг вниз обратно к стойке. */
const bowl = (x: number, top: number, bottom: number, w: number): Point[] => {
  const r = (bottom - top) / 2;
  return [[x, top], [x + w, top], ...arc(x + w, top + r, r, r, -90, 90, 10), [x, bottom]];
};

